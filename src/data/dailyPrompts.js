// Один индекс для всех карточек в течение календарного дня.
export function getDailyPromptIndex(date = new Date()) {
  const current = new Date(date.getFullYear(), date.getMonth(), date.getDate());
  const start = new Date(date.getFullYear(), 0, 1);
  const dayOfYear = Math.floor((current - start) / 86400000);
  return dayOfYear % 7;
}

// Подсказка одной темы на выбранную дату.
export function getDailyPrompt(topicId, date = new Date()) {
  const topic = dailyPrompts.find((item) => item.id === topicId);
  if (!topic) return null;
  return topic.prompts[getDailyPromptIndex(date)];
}

// Готовые данные для всех 15 карточек на одну дату.
export function getDailyCards(date = new Date()) {
  const index = getDailyPromptIndex(date);
  return dailyPrompts.map((topic) => ({
    id: topic.id,
    topic: topic.topic,
    image: topic.image,
    ...topic.prompts[index],
    // Этот текст передаётся агенту при нажатии на карточку.
    agentPrompt: `Продолжи разговор по теме «${topic.topic}». Заголовок подсказки: «${topic.prompts[index].title}». Контекст: ${topic.prompts[index].text} Задавай уточняющие вопросы и помогай практически, не ограничивайся повторением карточки.`,
  }));
}

